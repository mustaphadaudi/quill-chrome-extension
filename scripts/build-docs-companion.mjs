import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=name=>fs.readFileSync(root+name,'utf8');
const modes="const MODES = ['check','clearer','concise','professional','friendly','confident'];\n";
const prompts=read('background/prompts.js').replace(/export /g,'');
const engine=read('background/gemini.js').slice(0,read('background/gemini.js').indexOf('async function apiError')).replace(/^import .*\n/gm,'').replace(/export /g,'');
const output='// Generated by scripts/build-docs-companion.mjs from Quill source.\n'+modes+prompts+'\n'+engine+'\n'+read('shared/suggestions.js');
const target=root+'docs-companion/Engine.gs';
if(process.argv.includes('--check')){if(!fs.existsSync(target)||read('docs-companion/Engine.gs')!==output)throw new Error('Docs engine is out of date. Run node scripts/build-docs-companion.mjs.');}
else fs.writeFileSync(target,output);
